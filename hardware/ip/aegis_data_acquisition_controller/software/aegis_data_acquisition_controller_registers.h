#ifndef AEGIS_DATA_ACQUISITION_CONTROLLER_REGISTERS_H
#define AEGIS_DATA_ACQUISITION_CONTROLLER_REGISTERS_H
#include <io.h>
#define AEGIS_REGISTER_CONTROL 0x00
#define AEGIS_REGISTER_ADC_CONFIG 0x01
#define AEGIS_REGISTER_SAMPLE_DIVIDER 0x02
#define AEGIS_REGISTER_STATUS 0x03
#define AEGIS_REGISTER_ADC_RAW_SAMPLE 0x04
#define AEGIS_REGISTER_ADC_AVERAGE 0x05
#define AEGIS_REGISTER_FIFO_DATA 0x06
#define AEGIS_REGISTER_FIFO_COUNT 0x07
#define AEGIS_REGISTER_THRESHOLD_HIGH 0x08
#define AEGIS_REGISTER_THRESHOLD_LOW 0x09
#define AEGIS_REGISTER_FAULT_TIME 0x0A
#define AEGIS_REGISTER_FAULT_VALUE 0x0B
#define AEGIS_REGISTER_INTERRUPT_ENABLE 0x0C
#define AEGIS_REGISTER_INTERRUPT_STATUS 0x0D
#define AEGIS_REGISTER_TIMESTAMP 0x0E
#define AEGIS_REGISTER_PWM_PERIOD(channel) (0x10 + 2*(channel))
#define AEGIS_REGISTER_PWM_DUTY(channel) (0x11 + 2*(channel))
//CONTROL bits
#define AEGIS_CONTROL_ADC_ENABLE (1<<0)
#define AEGIS_CONTROL_PWM_ENABLE (1<<1)
#define AEGIS_CONTROL_FAILSAFE_ENABLE (1<<2)
#define AEGIS_CONTROL_SOFTWARE_FAULT (1<<3)
#define AEGIS_CONTROL_FAULT_CLEAR (1<<4)
//STATUS bits
#define AEGIS_STATUS_ADC_BUSY (1<<0)
#define AEGIS_STATUS_NEW_RAW_SAMPLE (1<<1)
#define AEGIS_STATUS_NEW_AVERAGE (1<<2)
#define AEGIS_STATUS_FIFO_EMPTY (1<<3)
#define AEGIS_STATUS_FIFO_HALF_FULL (1<<4)
#define AEGIS_STATUS_FIFO_FULL (1<<5)
#define AEGIS_STATUS_FAULT (1<<6)
#define AEGIS_STATUS_FAULT_HIGH (1<<7)
#define AEGIS_STATUS_FAULT_LOW (1<<8)
#define AEGIS_STATUS_FAULT_SOFTWARE (1<<9)
//INTERRUPT_ENABLE and INTERRUPT_STATUS bits
#define AEGIS_INTERRUPT_NEW_AVERAGE (1<<0)
#define AEGIS_INTERRUPT_FIFO_HALF_FULL (1<<1)
#define AEGIS_INTERRUPT_FAULT (1<<2)
//Field helpers
#define AEGIS_ADC_CONFIG_VALUE(channel,exponent) (((channel)&0x7)|(((exponent)&0x7)<<4))
#define AEGIS_SAMPLE_VALUE(word) ((word)&0xFFF)
#define AEGIS_SAMPLE_CHANNEL(word) (((word)>>12)&0x7)
//Register access
#define AEGIS_READ(base,register_offset) IORD(base,register_offset)
#define AEGIS_WRITE(base,register_offset,value) IOWR(base,register_offset,value)
#endif